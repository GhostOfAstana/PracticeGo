package main

import "fmt"

func NewtonThird(force float64) float64 {
	return -force
}

func main() {
	action := 1000.0
	reaction := NewtonThird(action)

	fmt.Println("Action:", action, "N")
	fmt.Println("Reaction:", reaction, "N")
}

// Законы Ньютона: Третий закон Ньютона утверждает, что на каждое действие есть равное и противоположное противодействие.
// В данном коде функция NewtonThird принимает силу (action) и возвращает противоположную силу (reaction).
// В функции main задается значение действия (action), вызывается функция NewtonThird для получения реакции (reaction) и выводятся результаты на экран.
// В данном примере, если действие равно 1000 Н, то реакция будет равна -1000 Н, что соответствует третьему закону Ньютона.
// Вывод программы:
// Action: 1000 N
// Reaction: -1000 N
// Таким образом, программа демонстрирует принцип действия и противодействия в физике.
// Важно отметить, что в реальной физике силы не всегда выражаются в виде отрицательных значений, но для демонстрации принципа действия и противодействия в данном примере используется отрицательное значение для реакции.
// В реальной физике силы могут быть направлены в разные стороны, и знак силы зависит от выбранной системы координат.
// В данном примере используется простая модель, где действие и противодействие представлены как противоположные значения одной и той же величины.
// Важно понимать, что третий закон Ньютона применим к взаимодействию двух объектов, и силы действуют на разные объекты. В данном коде мы рассматриваем только одну силу и ее противоположную реакцию для демонстрации принципа.
// Таким образом, данный код является наглядной иллюстрацией третьего закона Ньютона и может быть использован для образовательных целей в области физики.
// Важно отметить, что в реальной физике силы могут быть направлены в разные стороны, и знак силы зависит от выбранной системы координат.
