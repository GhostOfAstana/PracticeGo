package main

import "fmt"

func NewtonThird(force float64) float64 {
	return -force
}

func main() {
	action := 1000.0
	reaction := NewtonThird(action)

	fmt.Println("Action:", action, "N")
	fmt.Println("Reaction:", reaction, "N")
}

// Законы Ньютона: Третий закон Ньютона утверждает, что на каждое действие есть равное и противоположное противодействие.
// В данном коде функция NewtonThird принимает силу (action) и возвращает противоположную силу (reaction).
// В функции main задается значение действия (action), вызывается функция NewtonThird для получения реакции (reaction) и выводятся результаты на экран.
// В данном примере, если действие равно 1000 Н, то реакция будет равна -1000 Н, что соответствует третьему закону Ньютона.
// Вывод программы:
// Action: 1000 N
// Reaction: -1000 N
// Таким образом, программа демонстрирует принцип действия и противодействия в физике.
